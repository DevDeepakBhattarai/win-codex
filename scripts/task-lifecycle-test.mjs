import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { SubagentJobRegistry } from "../dist/subagent-jobs.js";
import { RalphRegistry, SupportCommandBus, ralphRegistrationHandler, taskActionHandler, startSubagentJob, ThreadPreparationCoordinator } from "../dist/chatgpt-support.js";
const root = await mkdtemp(path.join(os.tmpdir(), "task-lifecycle-"));
const token = "test-token";
const threadId = "11111111-1111-4111-8111-111111111111";
const url = `https://chatgpt.com/c/${threadId}`;
const jobs = await SubagentJobRegistry.open(root);
const registry = await RalphRegistry.open(root);
const commands = new SupportCommandBus(undefined, undefined, 0, undefined, registry, jobs);
const request = async (handler, body, params = {}) => {
  const response = { statusCode: 200, status(code) { this.statusCode = code; return this; }, json(value) { this.body = value; }, setHeader() {} };
  await handler({ body, params, get: (name) => name === "authorization" ? `Bearer ${token}` : undefined }, response);
  return response;
};
try {
  const job = await jobs.create({ threadId: "api:closed-worker" });
  await jobs.assignChild(job.jobId, { threadId, conversationUrl: url });
  await registry.register(url, { agentCreated: true, activity: "running" });
  const registration = ralphRegistrationHandler(registry, token, commands, jobs);
  const removed = await request(registration, { conversationUrl: url, removed: true });
  assert.equal(removed.statusCode, 200);
  assert.equal((await jobs.job(job.jobId)).state, "cancelled", "closing the worker tab must remove its pending task");
  assert.equal((await registry.threads()).length, 0);
  const noBrowser = taskActionHandler(jobs, registry, commands, async () => { throw new Error("Browser is gone"); }, token);
  const stranded = await jobs.create({ threadId: "api:missing-worker" });
  await jobs.assignChild(stranded.jobId, { threadId, conversationUrl: url });
  const cancelled = await request(noBrowser, { action: "cancel" }, { jobId: stranded.jobId });
  assert.equal(cancelled.statusCode, 200, "cancelling must not require a live tab or browser");
  assert.equal((await jobs.job(stranded.jobId)).state, "cancelled");
  await registry.register(url, { agentCreated: true });
  const pauseJob = await jobs.create({ threadId: "api:paused-worker" });
  await jobs.assignChild(pauseJob.jobId, { threadId, conversationUrl: url });
  const queued = commands.execute({ feature: "threadMessaging", kind: "inspect_thread", conversationUrl: url });
  const rejected = assert.rejects(queued, /paused/);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal((await request(noBrowser, { action: "pause" }, { jobId: pauseJob.jobId })).statusCode, 200);
  await rejected;
  assert.equal((await jobs.job(pauseJob.jobId)).paused, true);
  assert.equal((await registry.threads())[0].paused, true);
  assert.equal((await (await RalphRegistry.open(root)).threads())[0].paused, true, "pause survives restart");
  assert.deepEqual(await registry.due(Date.now() + 86400_000), []);
  await registry.register(url, { agentCreated: true, activity: "running", reactivate: true });
  assert.equal((await registry.threads())[0].paused, true, "activity observation cannot resume a paused thread");
  await assert.rejects(commands.execute({ feature: "threadMessaging", kind: "send_message", targetUrl: url, message: "Continue" }), /paused/);
  assert.throws(() => commands.reserveRecovery("browser", url), /Recovery conflicts/);
  assert.equal(await commands.claim("browser", ["ralph", "threadMessaging"], 0), undefined);
  assert.equal(await registry.scheduleNow(threadId), "paused", "Check now cannot bypass pause");
  assert.equal((await request(noBrowser, { action: "resume" }, { jobId: pauseJob.jobId })).statusCode, 200);
  assert.equal((await jobs.job(pauseJob.jobId)).paused, false);
  assert.equal((await registry.threads())[0].paused, false);
  assert.equal((await registry.due(Date.now() + 86400_000)).length, 1);
  const pausedThread = await request(registration, { conversationUrl: url, paused: true });
  assert.equal(pausedThread.statusCode, 200);
  assert.deepEqual(await registry.due(Date.now() + 86400_000), []);
  assert.equal((await jobs.job(pauseJob.jobId)).paused, true, "pausing a worker thread also pauses its task");
  await request(registration, { conversationUrl: url, paused: false });
  assert.equal((await jobs.job(pauseJob.jobId)).paused, false);
  await jobs.cancel(pauseJob.jobId);
  const startup = await jobs.create({ threadId: "api:startup-race" });
  const preparer = new ThreadPreparationCoordinator(commands, { hasThread: async () => false }, async () => {});
  const starting = startSubagentJob(startup, "Test startup cancellation", { commands, registry, jobs, preparer, launchBrowser: async () => {} });
  const startupRejected = assert.rejects(starting, /cancelled/);
  const creation = await commands.claim("browser", ["threadMessaging"], 1000);
  assert.equal(creation.kind, "send_message");
  assert.equal((await request(registration, { conversationUrl: url, paused: true })).statusCode, 200, "pausing another thread does not break an in-flight new-chat startup");
  assert.equal((await request(noBrowser, { action: "cancel" }, { jobId: startup.jobId })).statusCode, 200);
  const lateUrl = "https://chatgpt.com/c/22222222-2222-4222-8222-222222222222?temporary-chat=true";
  commands.complete({ commandId: creation.id, browserId: "browser", kind: "send_message", ok: true, result: { status: "sent", conversationUrl: lateUrl } });
  const cleanup = await commands.claim("browser", ["threadMessaging"], 1000);
  assert.equal(cleanup.kind, "stop_thread");
  assert.equal(cleanup.targetUrl, lateUrl);
  commands.complete({ commandId: cleanup.id, browserId: "browser", kind: "stop_thread", ok: true, result: { status: "stopped", conversationUrl: lateUrl } });
  await startupRejected;
  assert.equal((await jobs.job(startup.jobId)).childThreadId, undefined);
  assert.equal((await registry.threads()).some(thread => thread.conversationUrl === lateUrl), false);

  const pausedReport = await jobs.create({ threadId: "api:paused-report" });
  await jobs.assignChild(pausedReport.jobId, { threadId: "33333333-3333-4333-8333-333333333333", conversationUrl: "https://chatgpt.com/c/33333333-3333-4333-8333-333333333333" });
  await jobs.setPaused(pausedReport.jobId, true);
  await writeFile(pausedReport.resultPath, "Finished while automation was paused.");
  await jobs.collectReport(pausedReport.jobId);
  await new Promise(resolve => setTimeout(resolve, 30));
  assert.equal((await jobs.job(pausedReport.jobId)).state, "pending", "file watcher and direct collection respect task pause");
  await jobs.setPaused(pausedReport.jobId, false);
  await jobs.collectReport(pausedReport.jobId);
  assert.equal((await jobs.job(pausedReport.jobId)).state, "complete", "resume collects the waiting report");
  console.log("PASS: task/thread pause, offline cancellation, startup cancellation race, paused reports, explicit resume");
} finally { commands.close(); await jobs.close(); await rm(root, { recursive: true, force: true }); }
